def clean_query(query):
    """Clean a SQL query for execution"""
    if not isinstance(query, str):
        return str(query)
    
    # Remove trailing semicolon if present (for comparison)
    query = query.strip()
    if query.endswith(';'):
        query = query[:-1]
    
    return query

def execute_query(connection, query):
    """Execute a SQL query and return the results"""
    try:
        if connection is None or not connection.is_connected():
            return False, "MySQL Connection not available.", None
        
        cursor = connection.cursor(dictionary=True)
        cursor.execute(query)
        results = cursor.fetchall()
        cursor.close()
        return True, "Query executed successfully", results
    except Error as e:
        return False, str(e), None
    except Exception as e:
        return False, str(e), None

def compare_query_results(results1, results2):
    """
    Compare two query results for logical equivalence
    Returns True if results match, False otherwise
    """
    if results1 is None and results2 is None:
        return True
    
    if results1 is None or results2 is None:
        return False
    
    # Convert to DataFrames for easier comparison
    df1 = pd.DataFrame(results1)
    df2 = pd.DataFrame(results2)
    
    # Check if empty results (both should be empty)
    if df1.empty and df2.empty:
        return True
    
    # Check if dataframes have the same shape
    if df1.shape != df2.shape:
        return False
    
    # Check for same column names (ignoring case and order)
    cols1 = set(col.lower() for col in df1.columns)
    cols2 = set(col.lower() for col in df2.columns)
    if cols1 != cols2:
        return False
    
    # Normalize numeric types and precision for comparison
    for col in df1.columns:
        if pd.api.types.is_numeric_dtype(df1[col]):
            df1[col] = df1[col].astype(float)
            df2[col] = df2[col].astype(float)
            
            # Round to handle small floating point differences
            df1[col] = df1[col].round(6)
            df2[col] = df2[col].round(6)
    
    # Sort dataframes to ensure consistent comparison
    common_cols = list(cols1)
    
    try:
        df1_sorted = df1.sort_values(by=common_cols).reset_index(drop=True)
        df2_sorted = df2.sort_values(by=common_cols).reset_index(drop=True)
        
        # Check if dataframes are equal
        return df1_sorted.equals(df2_sorted)
    except:
        # If sorting fails, compare the sets of records
        records1 = [tuple(sorted(r.items())) for r in results1]
        records2 = [tuple(sorted(r.items())) for r in results2]
        return set(records1) == set(records2)

def get_sql_from_api(api_url, question, use_rag=False, timeout=30, max_retries=MAX_RETRIES, retry_delay=RETRY_DELAY):
    """
    Send a natural language question to the API and get the generated SQL query
    Returns (success, message, sql_query)
    """
    # Create a unique session ID for this request
    session_id = f"eval_{int(time.time())}_{hash(question) % 10000}"
    
    logger.info(f"Sending API request for query: '{question[:50]}...' (RAG: {use_rag})")
    
    # Prepare the API request
    url = f"{api_url}/query"
    payload = {
        "session_id": session_id,
        "question": question,
        "message_type": "question",
        "use_rag": use_rag
    }
    
    # Try with retries
    for attempt in range(max_retries):
        try:
            # Send the request
            logger.info(f"  → Sending request to {url} (Attempt {attempt+1}/{max_retries})")
            response = requests.post(url, json=payload, timeout=timeout)
            
            # Check for success
            if response.status_code != 200:
                logger.warning(f"  ✗ API Error: {response.status_code}")
                if attempt < max_retries - 1:
                    logger.info(f"  Retrying in {retry_delay} seconds...")
                    time.sleep(retry_delay)
                    continue
                return False, f"API Error: {response.status_code}", None
            
            # Extract the SQL query from the response
            response_data = response.json()
            sql_query = response_data.get("sql_query")
            
            if not sql_query:
                logger.warning(f"  ✗ No SQL query in API response")
                return False, "No SQL query in API response", None
            
            logger.info(f"  ✓ Received SQL query: '{sql_query[:50]}...'")
            return True, "Success", sql_query
        
        except Timeout:
            logger.warning(f"  ✗ API request timed out (Attempt {attempt+1}/{max_retries})")
            if attempt < max_retries - 1:
                logger.info(f"  Retrying in {retry_delay} seconds...")
                time.sleep(retry_delay)
            else:
                return False, "API request timed out after multiple attempts", None
        
        except ConnectionError:
            logger.warning(f"  ✗ API connection error (Attempt {attempt+1}/{max_retries})")
            if attempt < max_retries - 1:
                logger.info(f"  Retrying in {retry_delay} seconds...")
                time.sleep(retry_delay)
            else:
                return False, "API connection error after multiple attempts", None
        
        except Exception as e:
            logger.error(f"  ✗ Error: {str(e)}")
            if attempt < max_retries - 1:
                logger.info(f"  Retrying in {retry_delay} seconds...")
                time.sleep(retry_delay)
            else:
                return False, f"Error after multiple attempts: {str(e)}", None
    
    # If we reach here, all retries failed
    return False, "All API request attempts failed", None

def evaluate_query(row, connection, all_db_tables, api_url, timeout, verbose, use_rag=False, max_retries=MAX_RETRIES, retry_delay=RETRY_DELAY):
    """Evaluate a single query from the dataset"""
    try:
        # Extract data
        nl_query = row["Natural Language Query"]
        gold_sql = row["SQL Query"]
        
        # Get tables used by the query
        table_names_str = str(row.get("Table_Names", ""))
        specified_tables = []
        for table in [t.strip() for t in table_names_str.split(",") if t.strip()]:
            table = table.strip('[]')  # Remove brackets if present
            specified_tables.append(table)
        
        # Get SQL query from API
        api_success, api_message, generated_sql = get_sql_from_api(
            api_url, nl_query, use_rag, timeout, max_retries, retry_delay
        )
        
        if not api_success:
            if verbose:
                logger.warning(f"API Error for query: {nl_query}")
                logger.warning(f"Error: {api_message}")
            
            return {
                "nl_query": nl_query,
                "gold_sql": gold_sql,
                "generated_sql": None,
                "api_success": False,
                "api_error": api_message,
                "syntactically_correct": False,
                "logically_correct": False,
                "gold_execution_success": False,
                "generated_execution_success": False,
                "error_message": api_message
            }
        
        # Clean the queries
        gold_sql_clean = clean_query(gold_sql)
        generated_sql_clean = clean_query(generated_sql)
        
        # Test syntactical correctness
        syntax_success, syntax_message = test_query(
            connection, generated_sql_clean, specified_tables, all_db_tables, verbose
        )
        
        # If we can't test logical correctness without syntax, return early
        if not syntax_success:
            return {
                "nl_query": nl_query,
                "gold_sql": gold_sql_clean,
                "generated_sql": generated_sql_clean,
                "api_success": True,
                "syntactically_correct": False,
                "logically_correct": False,
                "gold_execution_success": False,
                "generated_execution_success": False,
                "error_message": syntax_message
            }
        
        # Execute both queries to test logical correctness
        gold_exec_success, gold_exec_message, gold_results = execute_query(connection, gold_sql_clean)
        gen_exec_success, gen_exec_message, gen_results = execute_query(connection, generated_sql_clean)
        
        # Determine logical correctness
        logically_correct = False
        if gold_exec_success and gen_exec_success:
            logically_correct = compare_query_results(gold_results, gen_results)
        
        return {
            "nl_query": nl_query,
            "gold_sql": gold_sql_clean,
            "generated_sql": generated_sql_clean,
            "api_success": True,
            "syntactically_correct": syntax_success,
            "logically_correct": logically_correct,
            "gold_execution_success": gold_exec_success,
            "generated_execution_success": gen_exec_success,
            "gold_error": "" if gold_exec_success else gold_exec_message,
            "generated_error": "" if gen_exec_success else gen_exec_message
        }
    
    except Exception as e:
        if verbose:
            logger.error(f"Evaluation error: {str(e)}")
        
        return {
            "nl_query": nl_query if 'nl_query' in locals() else "Unknown",
            "gold_sql": gold_sql if 'gold_sql' in locals() else "Unknown",
            "generated_sql": generated_sql_clean if 'generated_sql_clean' in locals() else "Unknown",
            "api_success": api_success if 'api_success' in locals() else False,
            "syntactically_correct": False,
            "logically_correct": False,
            "error_message": str(e)
        }

def format_metrics_table(metrics, title=None):
    """Format metrics data as a nice table"""
    table_data = []
    
    if title:
        table_data.append([f"--- {title} ---", ""])
    
    # Add main metrics
    table_data.append(["API Success Rate", f"{metrics['api_success_rate']:.2f}%"])
    table_data.append(["Syntactical Correctness", f"{metrics['syntactical_correctness']:.2f}%"])
    table_data.append(["Logical Correctness", f"{metrics['logical_correctness']:.2f}%"])
    table_data.append(["Logical Correctness (of Syntactically Correct)", 
                      f"{metrics['logical_of_syntactical']:.2f}%"])
    
    # Add query counts
    table_data.append(["", ""])
    table_data.append(["Total Queries", metrics['total_queries']])
    table_data.append(["API Successful Queries", metrics['api_success_count']])
    table_data.append(["Syntactically Correct Queries", metrics['syntactically_correct_count']])
    table_data.append(["Logically Correct Queries", metrics['logically_correct_count']])
    
    # Format as a nice table
    return tabulate(table_data, headers=["Metric", "Value"], tablefmt="grid")

