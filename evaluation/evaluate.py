def format_error_table(error_counts, title=None):
    """Format error data as a nice table"""
    table_data = []
    
    if title:
        table_data.append([f"--- {title} ---", ""])
    
    errors = [(error, count) for error, count in error_counts.items()]
    errors.sort(key=lambda x: x[1], reverse=True)
    
    # Take only top 10 errors for readability
    table_data.extend(errors[:10])
    
    # Format as a nice table
    return tabulate(table_data, headers=["Error", "Count"], tablefmt="grid")

def calculate_metrics(results):
    """Calculate metrics from evaluation results"""
    total_queries = len(results)
    api_success_count = sum(1 for r in results if r.get('api_success', False))
    syntactically_correct_count = sum(1 for r in results if r.get('syntactically_correct', False))
    logically_correct_count = sum(1 for r in results if r.get('logically_correct', False))
    
    # Calculate percentages
    api_success_rate = (api_success_count / total_queries) * 100 if total_queries > 0 else 0
    syntactical_correctness = (syntactically_correct_count / total_queries) * 100 if total_queries > 0 else 0
    logical_correctness = (logically_correct_count / total_queries) * 100 if total_queries > 0 else 0
    logical_of_syntactical = (logically_correct_count / syntactically_correct_count) * 100 if syntactically_correct_count > 0 else 0
    
    # Collect error types for syntactically incorrect queries
    syntax_errors = {}
    for r in results:
        if not r.get('syntactically_correct', True) and 'generated_error' in r:
            error = r['generated_error']
            # Truncate long error messages
            if len(error) > 100:
                error = error[:100] + "..."
            if error not in syntax_errors:
                syntax_errors[error] = 0
            syntax_errors[error] += 1
    
    # Create metrics dictionary
    return {
        'total_queries': total_queries,
        'api_success_count': api_success_count,
        'api_success_rate': api_success_rate,
        'syntactically_correct_count': syntactically_correct_count,
        'syntactical_correctness': syntactical_correctness,
        'logically_correct_count': logically_correct_count,
        'logical_correctness': logical_correctness,
        'logical_of_syntactical': logical_of_syntactical,
        'syntax_errors': syntax_errors
    }

def save_checkpoint(checkpoint_file, current_index, results_no_rag, results_rag, args):
    """Save checkpoint to resume from this point later"""
    try:
        checkpoint_data = {
            'current_index': current_index,
            'results_no_rag': results_no_rag,
            'results_rag': results_rag,
            'args': {
                'dataset': args.dataset,
                'api_url': args.api_url,
                'timeout': args.timeout,
                'compare_rag': args.compare_rag,
                'only_rag': args.only_rag,
                'only_no_rag': args.only_no_rag
            }
        }
        with open(checkpoint_file, 'w') as f:
            json.dump(checkpoint_data, f)
        logger.info(f"Checkpoint saved at index {current_index}")
    except Exception as e:
        logger.error(f"Failed to save checkpoint: {str(e)}")

def load_checkpoint(checkpoint_file):
    """Load checkpoint from file"""
    try:
        with open(checkpoint_file, 'r') as f:
            return json.load(f)
    except FileNotFoundError:
        logger.info(f"No checkpoint file found at {checkpoint_file}, starting fresh")
        return None
    except Exception as e:
        logger.error(f"Error loading checkpoint: {str(e)}")
        return None

def run_evaluation(df, connection, all_db_tables, args, use_rag=False, start_idx=0, existing_results=None):
    """Run evaluation on the dataset with the specified RAG setting"""
    rag_status = "RAG" if use_rag else "No RAG"
    logger.info(f"\n{'='*80}")
    logger.info(f"Starting evaluation with {rag_status} from index {start_idx}...")
    logger.info(f"{'='*80}")
    
    # Initialize or continue with existing results
    results = existing_results if existing_results else []
    start_time = time.time()
    
    # Process queries with progress bar
    for index, row in tqdm(df.iloc[start_idx:].iterrows(), total=len(df)-start_idx, desc=f"Evaluating with {rag_status}"):
        try:
            # Save checkpoint periodically if specified
            if args.checkpoint and index % 10 == 0 and index > start_idx:
                save_point = results.copy()
                if use_rag:
                    save_checkpoint(args.checkpoint, index, None, save_point, args)
                else:
                    save_checkpoint(args.checkpoint, index, save_point, None, args)
            
            # Reconnect periodically
            if index % 10 == 0 and index > start_idx:
                # Check connection and reconnect if needed
                if not connection or not connection.is_connected():
                    logger.info(f"\n[{index}/{len(df)}] Reconnecting to MySQL...")
                    connection = connect_to_mysql(args.host, args.user, args.password, args.database)
                    if not connection:
                        logger.error("Failed to reconnect to MySQL. Stopping evaluation.")
                        break
                    all_db_tables = get_all_tables(connection)
                
                # Print periodic status update
                elapsed_time = time.time() - start_time
                queries_per_second = (index - start_idx) / elapsed_time if elapsed_time > 0 else 0
                estimated_total_time = ((len(df) - start_idx) / queries_per_second) if queries_per_second > 0 else 0
                estimated_remaining = estimated_total_time - elapsed_time if estimated_total_time > 0 else 0
                
                logger.info(f"\n[{index}/{len(df)}] {rag_status} Progress update:")
                logger.info(f"  - Completed: {index-start_idx}/{len(df)-start_idx} queries ({(index-start_idx)/(len(df)-start_idx)*100:.1f}%)")
                logger.info(f"  - Elapsed time: {elapsed_time:.1f} seconds")
                logger.info(f"  - Estimated remaining: {estimated_remaining:.1f} seconds")
                logger.info(f"  - Queries per second: {queries_per_second:.2f}")
            
            logger.info(f"\n[{index+1}/{len(df)}] {rag_status} - Evaluating query: '{row['Natural Language Query'][:50]}...'")
            
            # Evaluate the query
            result = evaluate_query(
                row, connection, all_db_tables, args.api_url, args.timeout, args.verbose, use_rag,
                max_retries=args.max_retries, retry_delay=args.retry_delay
            )
            
            # Add RAG status and index to result
            result['use_rag'] = use_rag
            result['query_index'] = index
            results.append(result)
            
            # Print result summary
            if result['api_success']:
                if result['syntactically_correct']:
                    if result['logically_correct']:
                        logger.info(f"  ✓ {rag_status}: API Success, Syntax Correct, Logic Correct")
                    else:
                        logger.info(f"  ⚠ {rag_status}: API Success, Syntax Correct, Logic INCORRECT")
                else:
                    logger.info(f"  ⚠ {rag_status}: API Success, Syntax INCORRECT: {result.get('error_message', '')[:50]}")
            else:
                logger.info(f"  ✗ {rag_status}: API Failed: {result.get('api_error', '')[:50]}")
            
            # Brief pause to avoid overwhelming the API
            time.sleep(0.5)
            
        except KeyboardInterrupt:
            logger.warning(f"\n\nEvaluation interrupted at index {index}. Saving results up to this point.")
            # Save results obtained so far
            return results
        
        except Exception as e:
            logger.error(f"Unexpected error at index {index}: {str(e)}")
            # Try to continue with the next query
            continue
    
    return results

def main():
    """Main evaluation function"""
    args = parse_args()
    
    # Check for conflicting arguments
    if args.only_rag and args.only_no_rag:
        logger.error("Error: Cannot use --only-rag and --only-no-rag together.")
        return
    
    # Determine evaluation modes
    run_no_rag = not args.only_rag
    run_rag = args.compare_rag or args.only_rag
    
    # Check for checkpoint file
    checkpoint_data = None
    if args.checkpoint and os.path.exists(args.checkpoint):
        checkpoint_data = load_checkpoint(args.checkpoint)
        if checkpoint_data:
            logger.info(f"Resuming from checkpoint at index {checkpoint_data['current_index']}")
            args.start_idx = checkpoint_data['current_index']
    
    # Connect to MySQL
    connection = connect_to_mysql(args.host, args.user, args.password, args.database)
    if not connection:
        logger.error("Failed to connect to MySQL. Exiting.")
        return
    
    # Get all database tables
    all_db_tables = get_all_tables(connection)
    if not all_db_tables:
        logger.error("No tables found in database. Exiting.")
        connection.close()
        return
    
    logger.info(f"Connected to MySQL database. Found {len(all_db_tables)} tables.")
    
    # Load the gold dataset
    try:
        logger.info(f"Loading gold dataset from {args.dataset}...")
        df = pd.read_csv(args.dataset)
        
        # Check for required columns
        required_columns = ["Natural Language Query", "SQL Query"]
        missing_columns = [col for col in required_columns if col not in df.columns]
        if missing_columns:
            logger.error(f"Error: Missing required columns in dataset: {', '.join(missing_columns)}")
            connection.close()
            return
        
        # Apply limit if specified
        if args.limit:
            df = df.head(args.limit)
            logger.info(f"Limited to evaluating {args.limit} queries")
            
        total_queries = len(df)
        logger.info(f"Loaded {total_queries} queries for evaluation")
        logger.info("=" * 80)
        logger.info(f"EVALUATION PARAMETERS:")
        logger.info(f"  - API URL: {args.api_url}")
        logger.info(f"  - Timeout: {args.timeout} seconds")
        logger.info(f"  - Output file: {args.output}")
        logger.info(f"  - Start index: {args.start_idx}")
        logger.info(f"  - Max retries: {args.max_retries}")
        if args.checkpoint:
            logger.info(f"  - Checkpoint file: {args.checkpoint}")
        if run_rag and run_no_rag:
            logger.info(f"  - Mode: Comparing RAG vs non-RAG")
        elif run_rag:
            logger.info(f"  - Mode: RAG only")
        else:
            logger.info(f"  - Mode: Non-RAG only")
        logger.info("=" * 80)
        
    except Exception as e:
        logger.error(f"Error loading dataset: {e}")
        connection.close()
        return
    
    # Results containers
    results_no_rag = checkpoint_data['results_no_rag'] if checkpoint_data and 'results_no_rag' in checkpoint_data else []
    results_rag = checkpoint_data['results_rag'] if checkpoint_data and 'results_rag' in checkpoint_data else []
    
    try:
        # Run non-RAG evaluation if needed
        if run_no_rag:
            results_no_rag = run_evaluation(
                df, connection, all_db_tables, args, 
                use_rag=False, 
                start_idx=args.start_idx,
                existing_results=results_no_rag
            )
        
        # Run RAG evaluation if needed
        if run_rag:
            # Reconnect to ensure fresh connection
            if connection and connection.is_connected():
                connection.close()
            connection = connect_to_mysql(args.host, args.user, args.password, args.database)
            if not connection:
                logger.error("Failed to connect to MySQL for RAG evaluation. Exiting.")
                return
            all_db_tables = get_all_tables(connection)
            
            # If we already did non-RAG, we can start RAG from index 0
            rag_start_idx = 0 if run_no_rag else args.start_idx
            
            results_rag = run_evaluation(
                df, connection, all_db_tables, args, 
                use_rag=True, 
                start_idx=rag_start_idx,
                existing_results=results_rag
            )
        
    except KeyboardInterrupt:
        logger.warning("\nEvaluation interrupted by user. Processing results obtained so far...")
    
    finally:
        # Close the connection
        if connection and connection.is_connected():
            connection.close()
        
        # Calculate metrics
        metrics_no_rag = calculate_metrics(results_no_rag) if results_no_rag else None
        metrics_rag = calculate_metrics(results_rag) if results_rag else None
        
        # Print metrics tables
        logger.info("\nEvaluation Results:\n")
        
        if metrics_no_rag:
            logger.info(format_metrics_table(metrics_no_rag, "NON-RAG METRICS"))
            
            if metrics_no_rag['syntax_errors']:
                logger.info("\nTop Non-RAG Syntax Errors:\n")
                logger.info(format_error_table(metrics_no_rag['syntax_errors']))
        
        if metrics_rag:
            logger.info("\n" + format_metrics_table(metrics_rag, "RAG METRICS"))
            
            if metrics_rag['syntax_errors']:
                logger.info("\nTop RAG Syntax Errors:\n")
                logger.info(format_error_table(metrics_rag['syntax_errors']))
        
        # If both RAG and non-RAG were run, print comparison
        if metrics_no_rag and metrics_rag:
            logger.info("\nRAG vs NON-RAG COMPARISON:\n")
            logger.info(format_comparison_table(metrics_no_rag, metrics_rag))
        
        # Save results if output file specified
        if args.output:
            output_data = {
                'parameters': {
                    'api_url': args.api_url,
                    'timeout': args.timeout,
                    'ran_no_rag': run_no_rag,
                    'ran_rag': run_rag,
                    'max_retries': args.max_retries,
                    'start_idx': args.start_idx
                }
            }
            
            if metrics_no_rag:
                output_data['metrics_no_rag'] = metrics_no_rag
                output_data['details_no_rag'] = results_no_rag
            
            if metrics_rag:
                output_data['metrics_rag'] = metrics_rag
                output_data['details_rag'] = results_rag
            
            with open(args.output, 'w') as f:
                json.dump(output_data, f, indent=2)
            logger.info(f"\nDetailed results saved to {args.output}")
        
        logger.info("\nEvaluation complete.")

if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        logger.warning("\nEvaluation terminated by user.")
    except Exception as e:
        logger.error(f"Unexpected error: {str(e)}")
        import traceback
        logger.error(traceback.format_exc())

