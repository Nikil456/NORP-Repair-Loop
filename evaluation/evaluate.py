def parse_args():
    """Parse command-line arguments"""
    parser = argparse.ArgumentParser(description="Evaluate SQL generation against gold dataset")
    parser.add_argument("--dataset", type=str, required=True, help="Path to gold dataset CSV")
    parser.add_argument("--api-url", type=str, default=API_BASE_URL, help="Base URL for the API")
    parser.add_argument("--host", type=str, default="localhost", help="MySQL host")
